/****************************************************
*   使用说明：                                      *
*      要定义一个菜单，需要做以下几步工作           *
*      1、定义一个结构体数组                        *
*      2、如果这个菜单是子菜单，那么把上级菜单的    *
*         *ChildrenMenus指针指向该数组的首地址,     *
*         并且设置ParentMenus为上层目录的地址       *
*      3、如果这个菜单是跟菜单，那么直接将MenuPoint *
*         指针指向该数组的首地址                    *
*      4、通过写一个函数为该数组的每一个元素初始化 *
*      5、如果菜单项是最终选项，那么将*ChildrenMenus*
*         置为NULL，将函数指针*Subs指向实现功能的   *
*         函数。                                    *
****************************************************/

